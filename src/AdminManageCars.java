    class mytablemodel extends AbstractTableModel{

        @Override
        public int getRowCount() {
            return alr.size();
        }

        @Override
        public int getColumnCount() {
            return 11;
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
            car_details cd = alr.get(rowIndex);
            
            return switch (columnIndex) {
                case 0 -> cd.cid;
                case 1 -> cd.cnm;
                case 2 -> cd.brd;
                case 3 -> cd.cty;
                case 4 -> cd.fty;
                case 5 -> cd.pwod;
                case 6 -> cd.pwid;
                case 7 -> cd.secu;
                case 8 -> cd.desp;
                case 9 -> cd.nplt;
                case 10 -> cd.pht;
                default -> null;
            };
        }

        @Override
        public String getColumnName(int column) {
            String head[] = {"Car_id","Car_Name","Brand","Car_Type","Fuel_Type","Price_per_day_without_driver","Price_per_day_with_driver","Security","Description","Numberplate","Photo"};
            
            return head[column];
        }
    }
    

