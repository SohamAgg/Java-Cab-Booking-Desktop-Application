    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(jTable1.getSelectedRow() == -1){
            JOptionPane.showMessageDialog(this, "Please select a row first.");
        }
        else{
            int c = JOptionPane.showConfirmDialog(this, "Do you really want to remove this row ?", "Confrim Delete", JOptionPane.YES_NO_OPTION );
                if(c == JOptionPane.YES_OPTION){
                int idx = jTable1.getSelectedRow();
                int cdc = alr.get(idx).cid;
                alr.remove(idx);
                ResultSet rs = DBLoader.executeQuery("select * from car_details where car_id = "+cdc);
                try {
                    if(rs.next()){
                       rs.deleteRow();
                    }
                } catch (SQLException ex) {
                    Logger.getLogger(AdminManageCars.class.getName()).log(Level.SEVERE, null, ex);
                }
                mt.fireTableDataChanged();
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

