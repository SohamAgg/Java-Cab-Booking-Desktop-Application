    class mytablemodel extends AbstractTableModel{

        @Override
        public int getRowCount() {
            return alr.size();
        }

        @Override
        public int getColumnCount() {
            return 13;
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
            booking bk = alr.get(rowIndex);
            
            switch (columnIndex) {
                case 0:
                    return bk.booking_id;
                case 1:
                    return bk.car_id;
                case 2:
                    return bk.price_per_day;
                case 3:
                    return bk.start_date;
                case 4:
                    return bk.end_date;
                case 5:
                    return bk.no_of_days;
                case 6:
                    return bk.total_rent;
                case 7:
                    return bk.name;
                case 8:
                    return bk.mobile_no;
                case 9:
                    return bk.address;
                case 10:
                    return bk.email;
                case 11:
                    return bk.payment_status;
                case 12:
                    return bk.booking_status;
                default:
                    throw new AssertionError();
            }
        }

        @Override
        public String getColumnName(int column) {
            String head[] = {"Booking id","Car id","Price per Day","Start Date","End Date","No of Days","Rent","Name","Mobile No","Address","Email","Payment Status","Booking Status"};
            return head[column];
        }
    }

