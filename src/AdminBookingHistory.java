    public AdminBookingHistory() {
        rs = DBLoader.executeQuery("select * from booking");
        try {
            while(rs.next()){
                int booking_id = rs.getInt("booking_id");
                int car_id = rs.getInt("car_id");
                int price_per_day = rs.getInt("price_per_day");
                String start_date = rs.getString("start_date");
                String end_date = rs.getString("end_date");
                int no_of_days = rs.getInt("no_of_days");
                int total_rent = rs.getInt("total_rent");
                String name = rs.getString("name");
                String mobile_no = rs.getString("mobile_no");
                String address = rs.getString("address");
                String email = rs.getString("email");
                String payment_status = rs.getString("payment_status");
                String booking_status = rs.getString("booking_status");
                
                alr.add(new booking(booking_id, car_id, price_per_day, start_date, end_date, no_of_days, total_rent, name, mobile_no, address, email, payment_status, booking_status));
            }
        } catch (SQLException ex) {
            Logger.getLogger(AdminBookingHistory.class.getName()).log(Level.SEVERE, null, ex);
        }
        mt = new mytablemodel();
        ImageIcon im;
        try {
            im = new ImageIcon(ImageIO.read(new File("src\\myuploads\\generated-image (1).png")));
            setContentPane(new JLabel(im));
        } catch (IOException ex) {
            Logger.getLogger(Welcome.class.getName()).log(Level.SEVERE, null, ex);
        }
        repaint();
        initComponents();
        jPanel1.setOpaque(false);
        setSize(841,451);
        setExtendedState(MAXIMIZED_BOTH);
        setTitle("Admin Booking History");
        setLocationRelativeTo(null);
        jPanel1.requestFocus();
        backbutton.setText("\uD83E\uDC60");
    }

