    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(this.price == 0 || jDateChooser1.getDate() == null || jDateChooser2.getDate() == null){
            JOptionPane.showMessageDialog(this, "Please Select all the fields Appropriately");
        }
        else{
            String d1 = jDateChooser1.getDate().toString();
            String d2 = jDateChooser2.getDate().toString();
            int da1 = Integer.parseInt(d1.substring(8,10));
            int da2 = Integer.parseInt(d2.substring(8,10));
            if(da2 >= da1){
                int dy1 = day(d1.substring(4,7));
                int dy2 = day(d2.substring(4,7));
                d1 = da1+"-"+dy1+"-"+d1.substring(24);
                d2 = da2+"-"+dy2+"-"+d2.substring(24);
                int nod = da2-da1+1;
                int rent = this.price*nod;
                int security = Integer.parseInt(jLabel12.getText().substring(11));
                new BookingFinal(this.cid,this.price,d1,d2,nod,rent,security).setVisible(true);
                dispose();
            }
            else{
                JOptionPane.showMessageDialog(this, "The End Date Should not be Lesser than the Start Date");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

