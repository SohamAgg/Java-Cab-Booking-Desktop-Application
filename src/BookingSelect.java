    private void getcar(int i){
        ResultSet rs = DBLoader.executeQuery("select * from car_details where car_id =" + i);
        try {
            rs.next();
            jLabel2.setIcon(new ImageIcon( new ImageIcon(rs.getString("photo")).getImage().getScaledInstance(jLabel2.getWidth(), -1, Image.SCALE_SMOOTH)));
            jLabel3.setText("Car Name : "+rs.getString("Car_name"));
            jLabel4.setText("Brand : "+rs.getString("brand"));
            jLabel5.setText("Car Type : "+rs.getString("car_type"));
            jLabel11.setText("Fuel Type : "+rs.getString("fuel_type"));
            jLabel12.setText("Security : "+rs.getInt("security"));
            jRadioButton1.setText(rs.getString("Price_per_day_with_driver"));
            jRadioButton2.setText(rs.getString("Price_per_day_without_driver"));
        } catch (SQLException ex) {
            Logger.getLogger(BookingSelect.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

