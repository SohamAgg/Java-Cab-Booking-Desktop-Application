    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        JFileChooser JF1 = new JFileChooser();
        FileNameExtensionFilter filter = new FileNameExtensionFilter(
        "JPG , JPEG , GIF & PNG Images", "jpg", "gif" , "png", "jpeg");
        JF1.setFileFilter(filter);
        int returnVal = JF1.showOpenDialog(this);
        if(returnVal == JFileChooser.APPROVE_OPTION) {
            File f1 = JF1.getSelectedFile();
            String path = f1.getPath();
            int pa = path.indexOf("src");
            this.path = path.substring(pa);

            // Get Resized Image
            jLabel12.setIcon(new ImageIcon(new ImageIcon(this.path).getImage().getScaledInstance(130, 120, Image.SCALE_DEFAULT)));
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String cnm = jTextField1.getText();
        String brd = jComboBox1.getSelectedItem().toString();
        String cty = jComboBox2.getSelectedItem().toString();
        String fty = jComboBox3.getSelectedItem().toString();
        int pwid = Integer.parseInt(jTextField2.getText().isEmpty() ? "0" : jTextField2.getText());
        int pwod = Integer.parseInt(jTextField3.getText().isEmpty() ? "0" : jTextField3.getText());
        int secu = Integer.parseInt(jTextField4.getText().isEmpty() ? "0" : jTextField3.getText());
        String desp = jTextArea1.getText();
        String nplt = jTextField5.getText();
        String pht = this.path;
        if(cnm.isEmpty() || brd.equals("Select Brand") || cty.equals("Select Type") || fty.equals("Select Fuel Type") || pwid==0 || pwod==0 || secu==0 || nplt.isEmpty() || desp.isEmpty() || pht.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please fill all the fields");
        }
        else{
            ResultSet rs = DBLoader.executeQuery("select * from car_details where car_id = '"+this.id+"'");
            try {
                if(rs.next()){
                    rs.updateString("car_name", cnm);
                    rs.updateString("brand", brd);
                    rs.updateString("car_type", cty);
                    rs.updateString("fuel_type", fty);
                    rs.updateInt("price_per_day_with_driver", pwid);
                    rs.updateInt("price_per_day_without_driver", pwod);
                    rs.updateInt("security", secu);
                    rs.updateString("description", desp);
                    rs.updateString("numberplate", nplt);
                    rs.updateString("photo", pht);

                    rs.updateRow();
                    JOptionPane.showMessageDialog(this, "Car Edited Successfully");
                    try {
                        new AdminManageCars().setVisible(true);
                    } catch (IOException ex) {
                        Logger.getLogger(AdminChangePassword.class.getName()).log(Level.SEVERE, null, ex);
                    }
                    dispose();
                }
                else{
                    JOptionPane.showMessageDialog(this, "Car does not exist");
                }
            } catch (SQLException ex) {
                Logger.getLogger(AdminAddCar.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

