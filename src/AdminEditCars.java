    private void getdata(){
        ResultSet rs = DBLoader.executeQuery("select * from car_details where car_id = '"+this.id+"'");
        try {
            if(rs.next()){
                jTextField1.setText(rs.getString("car_name"));
                jComboBox1.setSelectedIndex(cboxselct(jComboBox1, rs.getString("brand")));
                jComboBox2.setSelectedIndex(cboxselct(jComboBox2, rs.getString("car_type")));
                jComboBox3.setSelectedIndex(cboxselct(jComboBox3, rs.getString("fuel_type")));
                jTextField2.setText(rs.getInt("Price_per_day_without_driver")+"");
                jTextField3.setText(rs.getInt("Price_per_day_with_driver")+"");
                jTextField4.setText(rs.getString("security")+"");
                jTextArea1.setText(rs.getString("description"));
                this.path = rs.getString("photo");
                jLabel12.setIcon(new ImageIcon(new ImageIcon(this.path).getImage().getScaledInstance(130, 120, Image.SCALE_DEFAULT)));
            }
        } catch (SQLException ex) {
            Logger.getLogger(AdminEditCars.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
