    int cboxselct(JComboBox c,String s){
        int a1 = c.getItemCount();
        int i = 0;
        int a = -1;
        while(i<a1){
            String s2 = c.getItemAt(i).toString();
            if(s.equals(s2)){
                a = i;
            }
            i++;
        }
        return a;
    }

